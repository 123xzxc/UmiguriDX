  '    var label = c.label ? " (" + esc(c.label) + ")" : "";',
  '    html += \'<div class="line">\';',
  '    html += \'<span class="mono grow\' + (c.revokedAt ? " revoked" : "") + \'">\' + esc(c.cardId) + label + "</span>";',
