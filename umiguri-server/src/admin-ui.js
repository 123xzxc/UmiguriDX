  '      html += \'<span class="tag">已吊销</span>\';',
  '    } else {',
  '      html += \'<span class="tag ok">有效</span>\';',
  '      html += \'<button class="small danger" data-act="revoke" data-id="\' + u.id + \'" data-card="\' + esc(c.cardId) + \'">吊销</button>\';',
  '    }',
  '    html += "</div>";',
  '  });',
  '  html += "</div>";',
  '  return html;',
  '}',
