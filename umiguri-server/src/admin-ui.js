  '  var html = \'<table><thead><tr><th>用户名</th><th>显示名</th><th>偏差</th><th>验证器</th><th>卡</th><th></th></tr></thead><tbody>\';',
  '  state.users.forEach(function (u) {',
  '    html += "<tr>";',
  '    html += \'<td class="mono">\' + esc(u.username) + "</td>";',
  '    html += "<td>" + esc(u.displayName) + "</td>";',
  '    html += "<td>" + u.rating + "</td>";',
  '    html += "<td>" + (u.totpBound ? \'<span class="tag ok">已绑定</span>\' : \'<span class="tag warn">未绑定</span>\') + "</td>";',
