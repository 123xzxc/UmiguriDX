  '  if (!res.ok || (data && data.ok === false)) {',
  '    var err = new Error((data && data.error) || ("请求失败 (" + res.status + ")"));',
  '    err.code = data && data.code;',
  '    throw err;',
  '  }',
  '  return data || {};',
  '}',
