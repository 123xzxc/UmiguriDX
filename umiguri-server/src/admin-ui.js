  '    html += "</td></tr>";',
  '    if (expanded[u.id]) {',
  '      html += \'<tr><td colspan="6">\' + renderCards(u) + "</td></tr>";',
  '    }',
  '  });',
  '  html += "</tbody></table>";',
  '  box.className = "";',
  '  box.innerHTML = html;',
  '}',
  '',
